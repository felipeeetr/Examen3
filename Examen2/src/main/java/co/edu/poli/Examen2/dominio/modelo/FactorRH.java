package co.edu.poli.Examen2.dominio.modelo;

/**
 * Enumeración que representa la presencia o ausencia del antígeno Rhesus (Factor RH).
 * 
 * <p>Utilizado para determinar la compatibilidad y clasificación sanguínea completa.</p>
 * 
 * @author Sistema de Laboratorio Clínico
 * @version 1.0
 */
public enum FactorRH {
    /** Indica la presencia del antígeno Rh (+). */
    POSITIVO,
    /** Indica la ausencia del antígeno Rh (-). */
    NEGATIVO
}
