package co.edu.poli.Examen2.dominio.modelo;

/**
 * Enumeración que representa los tipos de sangre reconocidos en el sistema médico.
 * 
 * <p>Define los cuatro grupos sanguíneos principales basados en el sistema ABO.</p>
 * 
 * @author Sistema de Laboratorio Clínico
 * @version 1.0
 */
public enum TipoSangre {
    /** Grupo sanguíneo A. */
    A,
    /** Grupo sanguíneo B. */
    B,
    /** Grupo sanguíneo AB (receptor universal en glóbulos rojos). */
    AB,
    /** Grupo sanguíneo O (donante universal en glóbulos rojos). */
    O
}
